Revival of Bharatanatyam  
========================

Introduction  
------------

The revival of Bharatanatyam in the early twentieth century transformed a threatened temple art into a global classical dance tradition. While legal and social forces had marginalized hereditary performers, cultural activists, artists, scholars, and institutions collaborated to restore respect for the art and reframe it as national heritage.

Key Forces of Revival  
---------------------

Several factors converged to spark revival:  

• Indian nationalist awakening  
• search for cultural identity  
• renewed appreciation of temple arts  
• modern reinterpreting of tradition  
• documentation efforts  
• artistic experimentation  

Individuals and institutions became catalysts for change.

Role of Rukmini Devi Arundale  
-----------------------------

Rukmini Devi played a defining role:  

• removed social stigma  
• presented dance on proscenium stages  
• formalized pedagogy structure  
• reintroduced temple aesthetics  
• used animal/bird symbolism in choreography  
• integrated costume reform  
• founded Kalakshetra institution  

Her reinterpretation emphasized spirituality, devotion, classical grammar, and refined movements.

E. Krishna Iyer  
----------------

He defended devadasi art publicly and advocated for recognition. His work contested colonial morality, created public discourse, and positioned dance as national cultural symbol.

Preservation of Devadasi Pedagogy  
----------------------------------

While revival recontextualized dance, artistic knowledge survived largely through hereditary teachers:

• Balasaraswati lineage emphasizing abhinaya depth  
• nattuvanars preserving rhythmic grammar  
• Tanjore Quartette compositions sustained  

This continuity ensured authenticity beneath modern restructuring.

Institutionalization  
--------------------

Revival brought institutional frameworks:

• Kalakshetra  
• Music Academy forums  
• sabhas supporting performances  
• national academies of arts  
• state cultural policies  

Formal curriculum structured training and professional pathways.

Artistic Innovations  
--------------------

Modern Bharatanatyam evolved through:  

• expanded repertoire  
• thematic productions  
• integration with literature and poetry  
• solo stage format development  
• new interpretations of mythology  
• global dissemination  

Artists explored identity and social themes while conserving classical integrity.

Politics of Revival  
-------------------

Debates arose concerning exclusion of devadasis, appropriation, class privilege, and erasure of hereditary voices. Recognition of these complexities is vital for ethical cultural preservation.

Globalization  
-------------

From mid-20th century onward:  

• Bharatanatyam spread globally  
• diasporic communities adopted training  
• universities established programs  
• hybrid choreographies emerged  

This expansion created dynamic dialogue between tradition and innovation.

Conclusion  
----------

Revival reimagined Bharatanatyam while drawing from ancient lineage. Its transformation from temple ritual to global stage reflects resilience, creativity, devotion, and cultural negotiation. The revival era safeguards heritage while enabling evolving artistic identity rooted in sacred aesthetics.

